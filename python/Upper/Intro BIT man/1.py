num1 = 10  # 1010
num2 = 4   # 0100

print("AND:", num1 & num2)      # 0000 = 0
print("OR:", num1 | num2)       # 1110 = 14
print("XOR:", num1 ^ num2)      # 1110 = 14
print("NOT num1:", ~num1)      
print("Left Shift num1:", num1 << 1)  # 10100 = 20
print("Right Shift num1:", num1 >> 1) # 0101 = 5

